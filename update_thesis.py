def apply_updates(doc, updates_dict):
    for idx, info in updates_dict.items():
        para = doc.paragraphs[idx]
        t = info['type']
        if t == 'simple':
            clear_and_set_text(para, info['text'])
        elif t == 'bold_prefix':
            set_bold_prefix_para(para, info['bold'], info['normal'])
        print(f'  [OK] para {idx}: {para.text[:40]}...')


def main():
    print('Loading merged document...')
    doc = Document('論文＿李昇峰_merged.docx')

    print('\n=== Updating Chapter 1 ===')
    apply_updates(doc, CH1_PARAS)

    print('\n=== Updating Chapter 2 ===')
    apply_updates(doc, CH2_PARAS)

    output_path = '論文＿李昇峰_v2.docx'
    doc.save(output_path)
    print(f'\nSaved to: {output_path}')


if __name__ == '__main__':
    main()
