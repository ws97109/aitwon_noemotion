def clear_and_set_text(para, new_text):
    """清除段落中所有 run 的文字，在第一個 run 寫入新文字，保留格式。"""
    if not para.runs:
        para.add_run(new_text)
        return
    # 保留第一個 run 的格式，清除其餘
    first_run = para.runs[0]
    # 紀錄格式
    bold = first_run.bold
    italic = first_run.italic
    underline = first_run.underline
    font_name = first_run.font.name
    font_size = first_run.font.size
    font_color = first_run.font.color.rgb if first_run.font.color and first_run.font.color.type else None

    # 清除所有 run 的文字
    for run in para.runs:
        run.text = ''

    # 在第一個 run 寫入新文字，套用原格式
    para.runs[0].text = new_text
    para.runs[0].bold = bold
    para.runs[0].italic = italic
    para.runs[0].underline = underline
    if font_name:
        para.runs[0].font.name = font_name
    if font_size:
        para.runs[0].font.size = font_size


def set_bold_prefix_para(para, bold_text, normal_text):
    """
    處理有粗體前綴的段落（如「情緒感知的重要性：...」）
    保持第一個 run 粗體，第二個 run 一般文字
    """
    if not para.runs:
        run1 = para.add_run(bold_text)
        run1.bold = True
        run2 = para.add_run(normal_text)
        return

    # 清除所有 run
    for run in para.runs:
        run.text = ''

    # 設第一個 run 為粗體前綴
    para.runs[0].text = bold_text
    para.runs[0].bold = True

    # 設第二個 run 為一般文字（若存在）
    if len(para.runs) >= 2:
        para.runs[1].text = normal_text
        para.runs[1].bold = False
    else:
        run2 = para.add_run(normal_text)
        run2.bold = False


